df = pd.read_csv("/content/Automobile_data.csv")

print("First Five Records:")
display(df.head())

print("\nDataset Shape:")
print(df.shape)

print("\nRequired Features:")
print("power_to_weight_ratio:", 'power_to_weight_ratio' in df.columns)
print("combined_mpg:", 'combined_mpg' in df.columns)

print("\nColumn Names:")
print(df.columns.tolist())

"""# Horsepower vs Price"""

plt.figure(figsize=(10, 6))

sns.scatterplot(
    data=df,
    x='horsepower',
    y='price',
    hue='fuel-type'
)

plt.title('Horsepower vs Price by Fuel Type')
plt.xlabel('Horsepower')
plt.ylabel('Price')
plt.legend(title='Fuel Type')
plt.show()

"""# Engine Size vs City MPG"""

plt.figure(figsize=(10, 6))

sns.scatterplot(
    data=df,
    x='engine-size',
    y='city-mpg',
    hue='fuel-type'
)

plt.title('Engine Size vs City MPG by Fuel Type')
plt.xlabel('Engine Size')
plt.ylabel('City MPG')
plt.legend(title='Fuel Type')
plt.show()

"""# Price Distribution by Body Style"""

plt.figure(figsize=(10, 6))

sns.boxplot(
    data=df,
    x='body-style',
    y='price'
)

plt.title('Price Distribution Across Body Styles')
plt.xlabel('Body Style')
plt.ylabel('Price')
plt.xticks(rotation=45)

plt.show()

"""# Price by Fuel Type and Engine Type"""

plt.figure(figsize=(10, 6))

sns.barplot(
    data=df,
    x='fuel-type',
    y='price',
    hue='engine-type',
    errorbar=None
)

plt.title('Average Price by Fuel Type and Engine Type')
plt.xlabel('Fuel Type')
plt.ylabel('Average Price')
plt.legend(title='Engine Type')

plt.show()

"""#  Correlation Heatmap

 Select numerical columns
"""

correlation_columns = [
    'engine-size',
    'horsepower',
    'curb-weight',
    'wheel-base',
    'length',
    'width',
    'height',
    'city-mpg',
    'highway-mpg',
    'combined_mpg',
    'power_to_weight_ratio',
    'price'
]

print("Available Columns:")
print(df.columns.tolist())

print("\nMissing Required Columns:")
print([col for col in correlation_columns if col not in df.columns])

correlation_data = df[correlation_columns].copy()

correlation_data = correlation_data.apply(
    pd.to_numeric, errors='coerce'
)

"""Calculate correlation"""

correlation_matrix = df[correlation_columns].corr()

correlation_matrix = correlation_data.corr()

"""# Create heatmap"""

plt.figure(figsize=(12, 8))

sns.heatmap(
    correlation_matrix,
    annot=True,
    cmap='coolwarm',
    fmt='.2f',
    linewidths=0.5
)

plt.title('Correlation Heatmap of Automobile Dataset')
plt.show()

"""#  Manufacturer-wise Analysis

 Group data by manufacturer
"""

manufacturer_analysis = df.groupby('make').agg({
    'price': 'mean',
    'horsepower': 'mean',
    'combined_mpg': 'mean'
}).reset_index()

print("Manufacturer-wise Average Analysis:")
display(manufacturer_analysis)

"""# Plot average price"""

plt.figure(figsize=(14, 6))

sns.barplot(
    data=manufacturer_analysis,
    x='make',
    y='price'
)

plt.title('Average Price by Manufacturer')
plt.xlabel('Manufacturer')
plt.ylabel('Average Price')
plt.xticks(rotation=90)
plt.show()

print("\nAverage Horsepower and Combined MPG:")
display(manufacturer_analysis[['make', 'horsepower', 'combined_mpg']])

