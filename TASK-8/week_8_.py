import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df=pd.read_csv("/content/drive/MyDrive/CSV/Copy of StudentsPerformance.csv")

df.head()

df.tail()

df.isnull()

df.info()

df.shape

avg=df.groupby(["parental level of education","lunch"])[
    ["math score","reading score","writing score"]
].mean()

avg.plot(kind="bar",figsize=(12,6))

plt.title("AVG Scores by Parental Education and Lunch Type")
plt.xlabel("Parental Education and Lunch Type")
plt.ylabel("Average Score")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

plt.figure(figsize=(8,5))
sns.boxplot(
    x="test preparation course",
    y="math score",
    data=df
)

plt.title("Math Score Variance Based on Test Prepar")
plt.xlabel("Test Prepar")
plt.ylabel("Math Score")
plt.show()

plt.figure(figsize=(7,5))
sns.scatterplot(
    x="math score",
    y="reading score",
    data=df
)

plt.title("Math Score vs Reading Score")
plt.show()

plt.figure(figsize=(7,5))

sns.scatterplot(
    x="math score",
    y="writing score",
    data=df
)

plt.title("Math vs Writing Score")
plt.show()

plt.figure(figsize=(7,5))

sns.scatterplot(
    x="reading score",
    y="writing score",
    data=df
)

plt.title("Reading vs Writing Score")
plt.show()

correlation=df[
    ["math score","reading score","writing score"]
].corr()

plt.figure(figsize=(7,5))

sns.heatmap(
    correlation,
    annot=True,
    cmap="coolwarm"
)

plt.title("Correlation Between Math, Reading and Writing Scores")
plt.show()