import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/content/drive/MyDrive/CSV/Automobile_data.csv")

print("First Five Records:")
df.head()

print("Last Five Records:")
df.tail()

print("Dataset Dimensions:")
print("Rows:", df.shape[0])
print("Columns:", df.shape[1])

print("Column Names:")
print(df.columns.tolist())

print("Dataset Information:")
df.info()

print("\nStatistical Summary:")
df.describe()

categorical_columns = df.select_dtypes(include=['object']).columns

print("\nCategorical Columns:")
print(categorical_columns.tolist())

numerical_columns = df.select_dtypes(include=['number']).columns

print("\nNumerical Columns:")
print(numerical_columns.tolist())

df.replace('?', np.nan, inplace=True)

print("Missing Values Count:")
print(df.isnull().sum())

print("\nMissing Values Percentage:")
missing_percentage = (df.isnull().sum() / len(df)) * 100
print(missing_percentage)

columns_to_fill = ['horsepower', 'peak-rpm', 'bore', 'stroke', 'price']

for col in columns_to_fill:
    df[col] = pd.to_numeric(df[col], errors='coerce')

for col in columns_to_fill:
    df[col] = df.groupby('make')[col].transform(
        lambda x: x.fillna(x.median())
    )

for col in columns_to_fill:
    df[col] = df[col].fillna(df[col].median())

print("Missing Values After Imputation:")
print(df[columns_to_fill].isnull().sum())

df['horsepower'] = df['horsepower'].astype(int)

float_columns = ['peak-rpm', 'price', 'bore', 'stroke']

for col in float_columns:
    df[col] = df[col].astype(float)

print("Updated Data Types:")
print(df[[
    'horsepower', 'peak-rpm', 'price', 'bore', 'stroke'
]].dtypes)

df['power_to_weight_ratio'] = (
    df['horsepower'] / df['curb-weight']
) * 1000

print("Power-to-Weight Ratio:")
display(df[['horsepower', 'curb-weight', 'power_to_weight_ratio']].head())

print("\nNew Column Added:")
print('power_to_weight_ratio' in df.columns)

df['combined_mpg'] = (
    df['city-mpg'] + df['highway-mpg']
) / 2

print("Combined MPG:")
display(df[['city-mpg', 'highway-mpg', 'combined_mpg']].head())

print("\nNew Column Added:")
print('combined_mpg' in df.columns)

body_style_analysis = df.groupby('body-style')[
    ['horsepower', 'engine-size', 'curb-weight',
     'price', 'combined_mpg']
].mean()

print("Average Values by Body Style:")
display(body_style_analysis)

print("\nBody Styles:")
print(body_style_analysis.index.tolist())

engine_location_analysis = df.groupby('engine-location')[
    ['horsepower', 'engine-size', 'curb-weight',
     'price', 'combined_mpg']
].mean()

print("Average Values by Engine Location:")
display(engine_location_analysis)

print("\nEngine Locations:")
print(engine_location_analysis.index.tolist())

print("Missing Values:")
print(df.isnull().sum())

print("\nData Types:")
print(df.dtypes)

print("\nDuplicate Rows:")
print(df.duplicated().sum())

print("\nNew Features:")
print('power_to_weight_ratio' in df.columns)
print('combined_mpg' in df.columns)

print("\nFinal Dataset Shape:")
print(df.shape)

df.to_csv('automobile_cleaned.csv', index=False)

print("\nCleaned Dataset Exported Successfully!")