import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/content/drive/MyDrive/CSV/kc_house_data.csv")

df

df.head()

df.tail()

df.info()

df.describe()

df.shape

df.columns

df.isnull().sum()

df.duplicated().sum()

features = [
    'bedrooms',
    'bathrooms',
    'sqft_living',
    'grade',
    'yr_built'
]

print("Property Features:")
print(df[features].head())

df['sale_year'] = pd.to_datetime(
    df['date']
).dt.year

df['property_age'] = (
    df['sale_year'] - df['yr_built']
)

df['is_renovated'] = np.where(
    df['yr_renovated'] > 0,
    'Yes',
    'No'
)

df[
    ['sale_year',
     'is_renovated']
].head()

df['price_per_sqft'] = df['price'] / df['sqft_living']

df[['price', 'sqft_living', 'price_per_sqft']].head()

df['date'] = pd.to_datetime(df['date'], errors='coerce')

df['sale_year'] = df['date'].dt.year

df['age_at_sale'] = df['sale_year'] - df['yr_built']

df['years_since_renovation'] = np.where(
    df['yr_renovated'].notna() &
    (df['yr_renovated'] > 0),
    df['sale_year'] - df['yr_renovated'],
     0

)

df[[
    'date',
    'sale_year',
    'yr_built',
    'age_at_sale',
    'yr_renovated',
    'years_since_renovation'
]].head()

df['price_per_sqft_living'] = (
    df['price'] / df['sqft_living']
)

df['price_per_sqft_lot'] = (
    df['price'] / df['sqft_lot']
)

df[['price', 'sqft_living', 'sqft_lot']].head()

plt.figure(figsize=(10, 5))
sns.boxplot(data=df['price_per_sqft_living'])
plt.title('Box Plot of Price per Square Foot')
plt.show()

plt.figure(figsize=(10, 5))
sns.boxplot(data=df['price_per_sqft_lot'])
plt.title('Box Plot of Price per Square Foot')
plt.show()

Q1 = df.quantile(0.25, numeric_only=True)
Q3 = df.quantile(0.75, numeric_only=True)
IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

df_numeric = df.select_dtypes(include=[np.number])

outliers = df_numeric[
    (df_numeric < lower_bound) | (df_numeric > upper_bound)
]

print("Q1:", Q1)
print("Q3:", Q3)
print("IQR:", IQR)
print("Lower Bound:", lower_bound)
print("Upper Bound:", upper_bound)
print("Number of Outliers:", len(outliers.dropna(how='all')))

df.to_csv("Studentperformance.csv", index=False)